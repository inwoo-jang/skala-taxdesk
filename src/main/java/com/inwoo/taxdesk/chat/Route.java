package com.inwoo.taxdesk.chat;

/**
 * 질문의 4분기(+거절). 이 실습의 고유 설계 포인트다.
 *
 * <p>어떤 부품을 부를지를 모델에게 매번 맡기지 않고 먼저 결정한다.
 * 특히 {@link #OUT_OF_SCOPE} 는 주 모델을 아예 호출하지 않는다 — 비용과 안전을 같은 지점에서 막는다.
 *
 * <p>거절이 정직하려면 업무 범위가 좁은 주체여야 한다. 증권사는 금융소득만 다루므로
 * "양도세는 안내드리지 않습니다"가 변명이 아니라 사실이 된다.
 */
public enum Route {

    /** 규정 질문 → RAG only. "배당소득세율이 뭔가요?" */
    REGULATION,

    /** 금액 계산 → Tool only. "이자 1200 배당 900이면?" */
    CALCULATION,

    /** 판정 필요 → RAG + Tool. "저 종합과세 대상인가요?" */
    HYBRID,

    /**
     * <b>연중 세무 플래닝</b> → Tool(역산). "배당 더 받아도 되나요?" "얼마까지 괜찮아요?"
     *
     * <p>이 서비스의 핵심 라우트다. 다른 라우트는 전부 <b>순방향</b>("얼마 받았으니 세금이 얼마")인데
     * 이것만 <b>역방향</b>이다 — "세금이 바뀌지 않으려면 얼마까지 받아도 되는가".
     *
     * <p>8월에 결정세액을 알려주는 것은 사실 쓸모가 적다. 아직 연도가 끝나지 않았고,
     * 고객은 <b>앞으로의 행동</b>을 정하려고 묻는다. 문턱까지 남은 금액을 알려줘야
     * 답이 의사결정에 쓰인다 — 사후 안내가 아니라 <b>사전 플래닝</b>이다.
     *
     * <p>역산은 LLM 이 절대 못 한다. 순방향 산수도 못 미더운데 역산은 말할 것도 없다.
     * "도구가 없으면 답이 안 나오는 질문"의 가장 선명한 사례다.
     *
     * <p>그리고 이 라우트가 투자자문 거절의 <b>대안</b>이 된다.
     * "배당주 추천해주세요"에는 답할 수 없지만
     * "세제 관점 여유는 474만원입니다"는 답할 수 있다 — 종목도 시점도 말하지 않으므로.
     *
     * @see com.inwoo.taxdesk.domain.TaxSimulation
     */
    SIMULATION,

    /**
     * 신청 → Tool + 승인 게이트. "세금 줄일 방법 없나요?" → 절세상품 자격 확인 신청.
     *
     * <p>증권사가 세무대리는 못 해도(세무사법 §2) <b>자사 절세상품의 세제 혜택 안내는 본업</b>이다.
     * 다만 가입 자격은 서류로 확인해야 하므로(조특법 §88의2③) 도구는 {@code PENDING} 까지만 만든다.
     *
     * <p>응답에 <b>투자권유가 섞이면 안 된다.</b> "가입하세요"가 아니라
     * "이런 세제 혜택이 있고, 자격 확인을 신청하실 수 있습니다"다.
     */
    ACTION,

    /**
     * 범위 밖 → 즉시 거절. 주 모델 호출 0회.
     *
     * <p><b>네 종류</b>를 구분해 안내한다. 앞의 셋은 소득세법 §14(종합소득에 합산되는가)로 갈리고,
     * 마지막 하나는 <b>다른 법</b>이 막는다.
     * <ul>
     *   <li><b>권한 밖 · 합산 가능</b> — "타사 계좌 배당도 조회해줘" → 조회 권한이 없습니다.
     *       금액을 알려주시면 합산해 드립니다 <b>(대안 제시)</b></li>
     *   <li><b>권한 밖 · 합산 가능</b> — "사업소득도 있는데요" → 계산해 드릴 수는 없지만
     *       소득금액을 알려주시면 합산해 드립니다. §14② 상 사업·근로·연금·기타소득은 종합소득이다</li>
     *   <li><b>진짜 범위 밖 · 합산 불가</b> — "양도세는 얼마예요?" → 안내드리지 않습니다.
     *       §14① 상 <b>분류과세</b>라 종합소득과세표준에 애초에 합산되지 않는다 (대안 없음)</li>
     *   <li><b>투자자문 · 시황 전망</b> — "이 주식 오를까요?" "지금 사도 되나요?" → 거절.
     *       우리는 세무 안내 데스크지 투자자문업자가 아니다. 자본시장법상 투자자문은
     *       등록한 자만 할 수 있고, 세무 상담 창구에서 종목 전망을 말하는 순간
     *       그건 안내가 아니라 <b>무등록 투자권유</b>가 된다</li>
     * </ul>
     * 앞의 둘에 대안이 없으면 그건 응대가 아니라 그냥 거절이다.
     * 셋째를 거절하는 이유는 "우리가 몰라서"가 아니라 <b>법적으로 합산 대상이 아니어서</b>다.
     *
     * <p>증권사를 주체로 골랐기 때문에 <b>법적 울타리가 둘</b>이 됐다 —
     * 세무사법(세무대리 불가)과 자본시장법(투자자문 불가). 세무 데스크인데 증권사가 운영한다는
     * 사실 자체가 거절의 근거를 두 배로 만든다.
     */
    OUT_OF_SCOPE
}
