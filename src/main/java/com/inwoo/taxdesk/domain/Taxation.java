package com.inwoo.taxdesk.domain;

/**
 * 금융소득 과세 방식의 판정 결과. <b>세액 계산보다 먼저 나와야 하는 값이다.</b>
 *
 * <p>순서가 우리 취향이 아니라 법 조문의 구조다 — 소득세법 §62 는
 * "종합과세기준금액을 초과하지 아니하는 경우에는 제2호(분리과세)의 금액으로 한다"고 못 박는다.
 */
public enum Taxation {

    /** 분리과세 종결. 원천징수 14% 로 끝나고 종합소득세 신고 대상이 아니다. */
    SEPARATE,

    /** 종합과세. 비교과세(소득세법 §62)로 세액을 정한다. */
    COMPREHENSIVE
}
