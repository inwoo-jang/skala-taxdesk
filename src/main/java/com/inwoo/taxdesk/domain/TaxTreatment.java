package com.inwoo.taxdesk.domain;

/**
 * 금융소득 한 건의 과세 방식. <b>{@code boolean taxExempt} 를 대체한다.</b>
 *
 * <p>비과세와 분리과세를 하나의 boolean 으로 뭉개면 안 된다. 결과는 "종합소득에 안 들어간다"로
 * 같아 보이지만 <b>빠지는 지점이 다르고, 세금을 내는지 여부가 다르다.</b>
 *
 * <pre>
 *   비과세    소득 발생 → 과세대상에서 제외        → 세금 자체가 없다
 *   분리과세  소득 발생 → 별도 세율로 과세 종결    → 세금은 냈고, 종합소득에만 안 들어간다
 *   종합과세  소득 발생 → 2천만원 초과분 합산      → 누진세율 + 비교과세
 * </pre>
 *
 * <p>답변 문구가 갈리기 때문에 구분이 필요하다 —
 * "세금이 없습니다"와 "9%로 과세가 끝났습니다"는 다른 말이다.
 */
public enum TaxTreatment {

    /** 종합과세 대상. 2,000만원 초과 판정에 들어간다. */
    TAXABLE,

    /**
     * 비과세 — 애초에 과세대상이 아니다. 세금 0.
     * 예: 비과세종합저축(조특법 §88의2, 원금 5천만원 한도) · ISA 비과세 한도 이내
     */
    TAX_FREE,

    /**
     * 분리과세 — 별도 세율로 과세가 종결된다. 종합소득과세표준에 합산하지 않는다.
     * 예: ISA 비과세 한도 초과분(조특법 §91의18, <b>9%</b>) ·
     *     고배당기업 특례배당소득(조특법 §104의27, 합산배제 <b>신청</b> 필요)
     */
    SEPARATE
}
