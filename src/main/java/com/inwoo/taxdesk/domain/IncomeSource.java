package com.inwoo.taxdesk.domain;

/**
 * 이 금융소득을 <b>우리가 어떻게 알게 됐는가.</b> 계산 전개에 그대로 표시된다.
 *
 * <p>초기 설계는 "SKALA증권 계좌만 안다"였다. 현실적이지 않아서 바꿨다 —
 * 마이데이터로 <b>예적금 이자는 전 금융사에서 자동 수집</b>되는 것이 실제 증권사 앱의 모습이다.
 * 다만 <b>연동에 동의한 기관만</b> 들어온다는 점이 그대로 남아서, 한계 고지와 수동 입력 대안은
 * 사라지지 않았다 — 오히려 대안이 <b>둘</b>로 늘었다("연동하시거나, 금액을 알려주시면").
 *
 * <p>구분이 필요한 이유는 <b>신뢰도가 다르기 때문</b>이다.
 * 답변에서 "저희가 확인한 금액"과 "고객님이 말씀하신 금액"이 섞이면 안 된다.
 */
public enum IncomeSource {

    /** SKALA증권 자사 계좌. 우리가 직접 지급하고 원천징수한 것 — 가장 확실하다. */
    OWN_ACCOUNT,

    /**
     * 마이데이터 연동 기관에서 자동 수집. 주로 은행 예적금 이자.
     * 확인된 금액이지만 <b>연동한 기관에 한한다</b>는 단서가 붙는다.
     */
    LINKED,

    /**
     * 고객이 말한 금액. 미연동 기관의 이자·배당, 타사 증권 배당 등.
     * 계산 전개에 <b>"고객 제공"</b> 으로 표시한다 — 여기부터는 우리가 보증하지 않는다.
     */
    DECLARED
}
