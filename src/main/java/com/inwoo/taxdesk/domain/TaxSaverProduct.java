package com.inwoo.taxdesk.domain;

/**
 * 절세상품. <b>증권사가 실제로 파는 것</b>이고, 가입에 <b>자격 확인</b>이 필요한 것만 다룬다.
 *
 * <p>"소득세 줄일 방법 없나요?"는 이 서비스에 반드시 들어오는 질문이다.
 * 그리고 증권사는 이 질문에 답할 자격이 있다 — 세무대리(세무사법 §2)와 달리,
 * 자사 상품의 <b>세제 혜택 안내</b>는 본업이다.
 *
 * <p>다만 답변은 <b>일반적인 세제 안내</b>여야 하고 특정 상품의 투자권유가 되면 안 된다.
 * 세무사법과는 별개로 자본시장법이 거는 제약이다 — 이 서비스에 걸린 <b>두 번째 법적 울타리</b>.
 */
public enum TaxSaverProduct {

    /**
     * 비과세종합저축 — 조특법 §88의2. 원금 5천만원 한도, <b>2028-12-31까지 가입분.</b>
     *
     * <p>자격이 §88의2① 각 호에 열거돼 있고 전부 <b>서류로 확인해야</b> 하는 것들이다 —
     * 65세 이상 기초연금 수급자 · 등록 장애인 · 독립유공자 · 상이자 · 기초생활수급자 ·
     * 고엽제후유의증환자 · 5·18민주화운동부상자.
     *
     * <p>같은 조 ③이 "가입대상의 <b>확인</b>"을 대통령령에 위임한다.
     * 승인 게이트가 이 서비스의 장식이 아니라 <b>법이 요구하는 절차</b>인 이유다.
     */
    TAX_FREE_SAVINGS,

    /**
     * ISA 서민형 — 조특법 §91의18②1호. 비과세 한도 <b>400만원</b>(일반형은 200만원).
     *
     * <p>직전 과세기간 총급여 5천만원 이하 또는 종합소득금액 3,800만원 이하여야 하고,
     * <b>소득확인증명서</b>로 확인한다. 우리는 고객의 근로·사업소득을 모르므로
     * (그래서 {@code otherIncome} 을 물어보는 것이다) 자격을 우리가 판정할 수 없다.
     */
    ISA_LOW_INCOME
}
